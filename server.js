app.post(
  '/api/scripts',
  express.raw({ type: 'application/octet-stream', limit: SCRIPT_MAX_BYTES }),
  async (req, res) => {
    const user = await getSessionUser(req);
    if (!user) return res.status(401).json({ success: false, message: 'Authentication required' });
    if (!Buffer.isBuffer(req.body) || req.body.length === 0) {
      return res.status(400).json({ success: false, message: 'Choose a non-empty script file' });
    }
    if (req.body.includes(0) || !Buffer.from(req.body.toString('utf8'), 'utf8').equals(req.body)) {
      return res.status(400).json({ success: false, message: 'Script files must be valid UTF-8 text' });
    }

    const title = String(req.query.title || '').trim();
    const description = String(req.query.description || '').trim();
    const rawFileName = String(req.query.fileName || '').replace(/\\/g, '/');
    const fileName = path.basename(rawFileName);
    const extension = path.extname(fileName).toLowerCase();
    if (title.length < 3 || title.length > 80) {
      return res.status(400).json({ success: false, message: 'Title must contain 3 to 80 characters' });
    }
    if (!description || description.length > 1000) {
      return res.status(400).json({ success: false, message: 'Description is required and must be at most 1000 characters' });
    }
    if (!fileName || fileName.length > 120 || !SCRIPT_EXTENSIONS.has(extension)) {
      return res.status(400).json({ success: false, message: 'Only .lua, .cs, .js, and .txt files are accepted' });
    }

    const pendingCount = await getSql(
      `SELECT COUNT(*) AS total FROM scripts WHERE owner_id = ${USE_POSTGRES ? '$1' : '?'} AND status = 'pending'`,
      [user.id]
    );
    if (Number(pendingCount.total) >= MAX_PENDING_SCRIPTS_PER_USER) {
      return res.status(429).json({ success: false, message: 'You already have 5 scripts waiting for moderation' });
    }

    const result = await runSql(
      USE_POSTGRES
        ? `INSERT INTO scripts (owner_id, title, description, file_name, file_data)
           VALUES ($1, $2, $3, $4, $5) RETURNING id`
        : `INSERT INTO scripts (owner_id, title, description, file_name, file_data)
           VALUES (?, ?, ?, ?, ?)`,
      [user.id, title, description, fileName, req.body]
    );
    const scriptId = USE_POSTGRES ? result.rows[0].id : result.id;
    const saved = await getSql(
      `SELECT s.id, s.title, s.description, s.file_name, s.status, s.moderation_note, s.created_at, s.updated_at,
              u.nickname AS owner_nickname
       FROM scripts s JOIN users u ON u.id = s.owner_id
       WHERE s.id = ${USE_POSTGRES ? '$1' : '?'}`,
      [scriptId]
    );
    return res.status(201).json({
      success: true,
      script: publicScript(saved),
      message: 'Скрипт надіслано на модерацію. Він з’явиться в каталозі тільки після схвалення.'
    });
  }
);

