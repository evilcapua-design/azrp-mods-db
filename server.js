async function startServer() {
  await initDatabase();

  const server = app.listen(PORT, HOST, () => {
    const url = `http://${HOST === '0.0.0.0' ? 'localhost' : HOST}:${PORT}`;
    console.log(`AZRP Mods app running at ${url}`);
    console.log(`Environment: ${ENVIRONMENT}`);
    console.log(`Telegram auth: ${BOT_TOKEN ? 'enabled' : 'disabled'}`);

    if (!BOT_TOKEN) {
      console.warn('Warning: Telegram auth is disabled. Set TELEGRAM_BOT_TOKEN and TELEGRAM_BOT_USERNAME for production use.');
    }
  });

  server.keepAliveTimeout = 65 * 1000;
  server.headersTimeout = 70 * 1000;
}

startServer().catch((error) => {
  console.error('Failed to start server:', error);
  process.exit(1);
});
