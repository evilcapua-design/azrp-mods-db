app.post('/api/admin/scripts/:id/review', async (req, res) => {
  const user = await getSessionUser(req);
  if (!user) return res.status(401).json({ success: false, message: 'Authentication required' });
  if (!ADMIN_TELEGRAM_IDS.has(String(user.telegram_id || ''))) {
    return res.status(403).json({ success: false, message: 'Administrator access required' });
  }

  const status = req.body?.status;
  const moderationNote = String(req.body?.note || '').trim().slice(0, 500);
  if (!['approved', 'rejected'].includes(status)) {
    return res.status(400).json({ success: false, message: 'Review status must be approved or rejected' });
  }

  const reviewed = await getSql(
    USE_POSTGRES
      ? `UPDATE scripts SET status = $1, moderation_note = $2, moderated_by = $3, updated_at = NOW()
         WHERE id = $4 AND status = 'pending' RETURNING id`
      : `UPDATE scripts SET status = ?, moderation_note = ?, moderated_by = ?, updated_at = CURRENT_TIMESTAMP
         WHERE id = ? AND status = 'pending' RETURNING id`,
    [status, moderationNote, user.id, req.params.id]
  );
  if (!reviewed) return res.status(404).json({ success: false, message: 'Pending script not found' });
  return res.json({ success: true, status });
});

